#!/usr/bin/env node
// ENC-TSK-S60-0A (ENC-PLN-106, Design System v1.1 spec DOC-8253497AC9FC section 3).
//
// Generates frontend/design-system-2/v2/roles.css from frontend/design-system-2/tokens.json.
//
// tokens.json is the v1.1 design copy (three tiers: primitives, roles, component tokens).
// The app already loads colors_and_type.css and v2/tokens.css. This generator emits only the
// tokens those two files do not define, so the change is additive: no existing custom
// property changes value. It refuses to run if a token in tokens.json would redefine an
// existing name with a different value.
//
// Usage:
//   node frontend/design-system-2/scripts/build-roles-css.mjs          write v2/roles.css
//   node frontend/design-system-2/scripts/build-roles-css.mjs --check  exit 1 if v2/roles.css is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const DS = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(DS, 'v2', 'roles.css')

const tokens = JSON.parse(readFileSync(join(DS, 'tokens.json'), 'utf8'))
const existingCss =
  readFileSync(join(DS, 'colors_and_type.css'), 'utf8') + readFileSync(join(DS, 'v2', 'tokens.css'), 'utf8')

const existing = new Map()
for (const m of existingCss.matchAll(/--([a-z0-9_-]+)\s*:\s*([^;]+);/g)) existing.set(m[1], m[2].trim())

const norm = (v) => String(v).replace(/\s+/g, '').toLowerCase()

// tokens.json writes an alias as {name}; CSS reads it as var(--name).
const toCss = (v) => String(v).replace(/\{([a-z0-9_-]+)\}/g, 'var(--$1)')

// Type variables the v1.1 spec adds (section 3.8). tokens.json has no family for them;
// the design copy keeps them in components/bundle.css.
const TYPE_VARS = [
  ['text-2xs', '0.6875rem', '11px. Badges, timestamps, micro labels.'],
  ['text-row', '0.84375rem', '13.5px. Feed row title.'],
  ['tracking-id', '0.01em', 'Record IDs.'],
  ['lh-none', '1', 'Single-line controls and glyphs.'],
]

// Names the app reached for and found undefined (spec 3.7, catalog 3.3). Each now resolves
// to its role, so a var(--name, #fallback) stops falling back.
const COMPAT = [
  ['bg-elevated', 'var(--surface-raised)'],
  ['bg-inset', 'var(--surface-sunken)'],
  ['bg-void', 'var(--canvas)'],
  ['status-success-fg', 'var(--success-text)'],
  ['status-warning-fg', 'var(--warning-text)'],
  ['status-danger-fg', 'var(--danger-text)'],
]

const FAMILIES = [
  ['color', 'Color: primitives, alpha tints, roles (core, status, rail, urgency, level, tag, operational, diff, document type)'],
  ['spacing', 'Spacing and component sizes'],
  ['radius', 'Radius'],
  ['shadow', 'Shadow'],
  ['size', 'Size and reading widths'],
  ['zIndex', 'Z-index'],
  ['breakpoint', 'Breakpoints (reference values; media queries cannot read custom properties)'],
]

const lines = []
const conflicts = []
const deprecated = []
const kept = []

for (const [family, title] of FAMILIES) {
  const block = []
  for (const t of tokens[family]?.tokens ?? []) {
    const raw = typeof t.value === 'object' && t.value !== null ? t.value.dark : t.value
    const value = toCss(raw)
    if (/^Deprecated/i.test(t.usage ?? '')) deprecated.push([t.name, t.usage.replace(/\s+/g, ' ')])
    if (existing.has(t.name)) {
      if (norm(existing.get(t.name)) !== norm(value)) conflicts.push(`${t.name}: existing ${existing.get(t.name)} vs tokens.json ${value}`)
      else kept.push(t.name)
      continue
    }
    block.push(`  --${t.name}: ${value};`)
  }
  if (block.length) lines.push(`  /* ${title} */`, ...block, '')
}

if (conflicts.length) {
  console.error('[build-roles-css] tokens.json would change existing custom properties:\n  ' + conflicts.join('\n  '))
  process.exit(2)
}

const typeBlock = TYPE_VARS.filter(([n]) => !existing.has(n)).map(([n, v, u]) => `  --${n}: ${v}; /* ${u} */`)
if (typeBlock.length) lines.push('  /* Type (spec 3.8) */', ...typeBlock, '')
lines.push('  /* Names the app used before they existed (spec 3.7) */', ...COMPAT.map(([n, v]) => `  --${n}: ${v};`))

const header = `/* GENERATED by frontend/design-system-2/scripts/build-roles-css.mjs from tokens.json
 * (Enceladus Design System v1.1, tokens.json version ${tokens.version}). Do not edit by hand:
 * edit tokens.json and rerun the script.
 *
 * Loaded after colors_and_type.css and v2/tokens.css. It defines only names those files do
 * not, so no existing value changes. ${kept.length} tokens in tokens.json are already defined
 * there with the same value and are not repeated here.
 *
 * Tiers: components read roles (canvas, surface, text, accent, border, status-<role>-*, ...);
 * roles alias primitives (enc-*, tint-*). Brand words never appear in role names.
 *
 * Deprecated (value kept, defined in colors_and_type.css or v2/tokens.css):
${deprecated.map(([n, u]) => ` *   --${n}: ${u.replace(/^Deprecated:\s*/i, '').replace(/\*\//g, '* /')}`).join('\n')}
 */
`

const css = `${header}
:root {
${lines.join('\n')}
}
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    // missing file is stale
  }
  if (current !== css) {
    console.error('[build-roles-css] v2/roles.css is stale; run node frontend/design-system-2/scripts/build-roles-css.mjs')
    process.exit(1)
  }
  console.log('[build-roles-css] v2/roles.css is current')
} else {
  writeFileSync(OUT, css)
  console.log(`[build-roles-css] wrote v2/roles.css (${lines.filter((l) => l.startsWith('  --')).length} properties)`)
}
