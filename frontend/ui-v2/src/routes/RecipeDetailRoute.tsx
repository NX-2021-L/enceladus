import { SchemaForm, contractFromCaps } from '@io-kit/schema_form'
import { checkInputs, isDryRunPlan } from '@io-kit/recipes'
import type { DryRunPlan, RecipeDefinition, RecipeHead, RunClient } from '@io-kit/recipes'
import { Table } from '../components/StackedTable'
