const inputColumns: TableColumnDefinition<InputRow>[] = [
  { id: 'name', header: 'Input', cell: (r) => <code>{r.name}</code> },
  { id: 'required', header: 'Required', cell: (r) => (r.required ? 'required' : 'optional') },
  { id: 'summary', header: 'Schema', cell: (r) => r.summary },
]

interface VersionRow {
  version: string
  status: string
  content_hash: string
}
const versionColumns: TableColumnDefinition<VersionRow>[] = [
  { id: 'version', header: 'Version', cell: (r) => r.version },
  { id: 'status', header: 'Lifecycle', cell: (r) => <span className="ev2-recipes__state" data-state={r.status}>{r.status}</span> },
  { id: 'hash', header: 'Content hash', cell: (r) => <code className="ev2-recipes__hash">{r.content_hash}</code> },
]

/** Dry run all (zero writes, plan inline) or Run to next gate (navigates to the run page); the inputs form is generated by the kit. */
function StartPanel(props: { client: RunClient; recipeId: string; version: string; project: string; definition: RecipeDefinition }) {
  const { client, recipeId, version, project, definition } = props
  const navigate = useNavigate()
  const [values, setValues] = useState<Record<string, unknown>>({})
  const [plan, setPlan] = useState<DryRunPlan | undefined>()
  const [busy, setBusy] = useState<string | undefined>()
  const [error, setError] = useState<string | undefined>()
  // Lazy state: one contract per mounted panel (the panel is keyed by recipe and version).
  const [contract] = useState(() =>
      contractFromCaps('recipes', {
        name: `recipe_run.start:${recipeId}`,
        title: `Start ${recipeId}`,
        inputSchema: definition.inputs,
        outputSchema: null,
        annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false },
        requiresGovernanceHash: false,
        via: 'top-level',
      } as never),
  )
  async function start(mode: 'dry_run' | 'to_next_gate', inputs: Record<string, unknown>) {
    const problems = checkInputs(definition.inputs, inputs)
    if (problems.length > 0) {
      setError(problems.join('; '))
      return
    }
    setBusy(mode)
    setError(undefined)
    try {
      const out = await client.startRun({ recipeId, version, inputs, mode, idempotencyKey: newIdempotencyKey(), definition })
      if (isDryRunPlan(out)) setPlan(out)
      else await navigate({ to: '/recipes/runs/$runId', params: { runId: out.run_id }, search: { project } })
    } catch (e) {
      setError(errMsg(e))
    } finally {
      setBusy(undefined)
    }
  }
  return (
    <section className="ev2-recipes__panel" aria-label="Start recipe">
      <Header variant="h2">Start</Header>
      <SchemaForm
        contract={contract}
        submitLabel="Run to next gate"
        onValueChange={(v: unknown) => setValues((v ?? {}) as Record<string, unknown>)}
        onSubmit={(args: unknown) => void start('to_next_gate', (args ?? {}) as Record<string, unknown>)}
      />
      <div className="ev2-recipes__actions">
        <button type="button" disabled={busy !== undefined} onClick={() => void start('dry_run', values)}>
          {busy === 'dry_run' ? 'Planning...' : 'Dry run all'}
        </button>
      </div>
      {busy === 'to_next_gate' ? <p role="status">Starting run...</p> : null}
      {error ? <p role="alert">{error}</p> : null}
      {plan ? <RecipePlanView plan={plan} /> : null}
    </section>
  )
}

/** /recipes/:recipeId: lifecycle, declared inputs, tools, projects, features, versions; dry run and start. */
export function RecipeDetailRoute() {
  const { recipeId = '' } = useParams({ strict: false }) as { recipeId?: string }
  const { project } = parseRecipesSearch(useSearch({ strict: false }) as Record<string, unknown>)
  useDocumentTitle(recipeId || 'Recipe')
  const client = createRecipeClient(project)
  const q = useQuery({ queryKey: ['recipes', 'get', project, recipeId, 'detail'], queryFn: () => client.recipes.get({ recipeId }) })
  if (q.isPending) return <div className="ev2-recipes"><PageHeader title={recipeId} /><p role="status">Loading recipe...</p></div>
  if (q.isError || !q.data) {
    return <div className="ev2-recipes"><PageHeader title={recipeId} /><p role="alert">Failed to load recipe: {errMsg(q.error)}</p></div>
  }
  const head = q.data.head as unknown as RecipeHead
  const version = versionOf(q.data)
  const def = version?.definition
  const features = head.related_feature_ids ?? []
  return (
    <div className="ev2-recipes">
      <PageHeader
        title={head.name || recipeId}
        description={def?.description ?? 'No published version yet.'}
        actions={<Link to="/recipes" search={{ project }} className="ev2-recipes__link">All recipes</Link>}
      />
      <dl className="ev2-recipes__facts">
        <dt>Record</dt><dd><code>{head.recipe_id}</code></dd>
        <dt>Lifecycle</dt><dd><span className="ev2-recipes__state" data-state={version?.status ?? 'draft'}>{version?.status ?? 'draft'}</span> (version {version?.version ?? '-'}, {q.data.resolved})</dd>
        <dt>Owner</dt><dd>{head.owner}</dd>
        <dt>Projects</dt><dd>{head.project_ids.join(', ') || '-'}</dd>
        <dt>Features</dt>
        <dd>
          {features.length === 0 ? '-' : features.map((f) => (
            <Link key={f} to="/$project/feature/$id" params={{ project, id: f }} className="ev2-recipes__link">{f} </Link>
          ))}
        </dd>
        <dt>Tools</dt><dd>{def?.tools.length ? def.tools.map((t) => <code key={t} className="ev2-recipes__tool">{t}</code>) : '-'}</dd>
      </dl>
      <section className="ev2-recipes__panel" aria-label="Declared inputs">
        <Header variant="h2">Declared inputs</Header>
        <Table<InputRow> columnDefinitions={inputColumns} items={inputRows(def?.inputs)} trackBy="name" empty="No declared inputs." />
      </section>
      <section className="ev2-recipes__panel" aria-label="Versions">
        <Header variant="h2" counter={`(${q.data.versions.length})`}>Versions</Header>
        <Table<VersionRow> columnDefinitions={versionColumns} items={q.data.versions} trackBy="version" empty="No versions." />
      </section>
      {def && version ? <StartPanel key={`${recipeId}@${version.version}`} client={client} recipeId={recipeId} version={version.version} project={project} definition={def} /> : null}
    </div>
  )
}
